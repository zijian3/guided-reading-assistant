import assert from "node:assert/strict";
import {readFile, stat} from "node:fs/promises";
const manifest = JSON.parse(await readFile("manifest.json","utf8"));
const pkg = JSON.parse(await readFile("package.json","utf8"));
const versions = JSON.parse(await readFile("versions.json","utf8"));
assert.match(manifest.id,/^[a-z]+(?:-[a-z]+)*$/);
assert.ok(!manifest.id.includes("obsidian") && !manifest.id.endsWith("plugin"));
assert.match(manifest.name,/^[A-Za-z0-9 ()+\-]+$/);
assert.ok(!/obsidian|plugin/i.test(manifest.name));
assert.match(manifest.version,/^\d+\.\d+\.\d+$/);
assert.equal(manifest.version,pkg.version); assert.equal(versions[manifest.version],manifest.minAppVersion);
assert.equal(manifest.isDesktopOnly,true);
assert.ok(manifest.description.length <= 250 && manifest.description.endsWith("."));
if (process.env.RELEASE_TAG) assert.equal(process.env.RELEASE_TAG,manifest.version);
for (const file of ["README.md","README.zh-CN.md","LICENSE","NOTICE.md","dist/main.js","dist/manifest.json","dist/styles.css"]) assert.ok((await stat(file)).size > 0,file);
assert.deepEqual(JSON.parse(await readFile("dist/manifest.json","utf8")),manifest);
const bundle = await readFile("dist/main.js","utf8");
assert.ok(bundle.includes("MIT License"));
assert.ok(!bundle.includes("vendor/segment-ai") && !bundle.includes("lacan-translation-helper"));
console.log(`Validated ${manifest.id} ${manifest.version} and release assets.`);
